#!/usr/bin/env python
"""Generate the HTTP route layer from the vendored OpenAPI specs (#3137 stretch, ADR-0005).

    uv run python scripts/gen_routes.py           # write generated/{system,site}_routes.py
    uv run python scripts/gen_routes.py --check   # exit 1 when a committed file drifts

One builder function per spec operation, named after its operationId in snake_case, taking
the path parameters as keyword-or-positional `str` arguments (percent-encoded with
`safe=""`, so nested slugs like `unit-1/lesson-2` stay one segment). Each returns a `Route`
with the method, the full request path, and the auth the spec's `security` requires. The
hand-written client (`client/system_api.py`, `client/site_api.py`) keeps request bodies and
response handling and asks these builders for where to send things, so a renamed or moved
route is "regenerate", and a removed one fails mypy/imports instead of a user's call.

Site API paths get the `/_sites/{site}` prefix HAXcms mounts every site under; the output is
deterministic (spec order, no timestamps) so `--check` can diff.
"""

from __future__ import annotations

import argparse
import difflib
import keyword
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPECS = ROOT / "specs"
GENERATED = ROOT / "src" / "haxcms_mcp" / "generated"
METHODS = ("get", "post", "put", "patch", "delete")

TARGETS = (
    # (spec file, output module, label, site-scoped)
    ("system-spec.yaml", "system_routes.py", "system", False),
    ("site-spec.yaml", "site_routes.py", "site", True),
)


def snake(name: str) -> str:
    """operationId -> python identifier (`getItemByIdOrSlug` -> `get_item_by_id_or_slug`)."""
    text = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    text = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", text)
    text = re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_").lower()
    return f"{text}_" if keyword.iskeyword(text) else text


def auth_mode(security: Any) -> str:
    """The client AuthMode a spec `security` list requires (no requirement -> "none")."""
    keys = {key for requirement in (security or []) for key in requirement}
    if "siteTokenHeader" in keys:
        return "bearer+site"
    if "userTokenHeader" in keys:
        return "bearer+user"
    if "bearerAuth" in keys:
        return "bearer"
    return "none"


def operations(spec: dict[str, Any]) -> list[tuple[str, str, str, list[str], str, str]]:
    """(operation_id, METHOD, path template, path params, auth, summary) in spec order."""
    default_security = spec.get("security")
    found = []
    for path, item in (spec.get("paths") or {}).items():
        for method in METHODS:
            operation = item.get(method)
            if not isinstance(operation, dict):
                continue
            op_id = operation.get("operationId")
            if not op_id:
                raise SystemExit(f"{method.upper()} {path} has no operationId")
            params = re.findall(r"\{([^}]+)\}", path)
            security = operation.get("security", default_security)
            summary = " ".join(str(operation.get("summary") or "").split())
            found.append((op_id, method.upper(), path, params, auth_mode(security), summary))
    return found


def render(spec_name: str, label: str, site_scoped: bool) -> str:
    spec = yaml.safe_load((SPECS / spec_name).read_text(encoding="utf-8"))
    ops = operations(spec)
    names = [snake(op[0]) for op in ops]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise SystemExit(f"{spec_name}: operationIds collide after snake_case: {duplicates}")

    out: list[str] = [
        f"# GENERATED by scripts/gen_routes.py from specs/{spec_name}. Do not edit.",
        f'"""HAXcms {label} API routes: one builder per spec operation (ADR-0005)."""',
        "",
        "from __future__ import annotations",
        "",
        "from haxcms_mcp.generated.route import Route, q",
        "",
    ]
    table: list[str] = []
    for (op_id, method, path, params, auth, summary), name in zip(ops, names, strict=True):
        args = [snake(p) for p in params]
        if site_scoped:
            args = ["site", *args]
        signature = ", ".join(f"{a}: str" for a in args)
        rendered = path
        for raw, arg in zip(params, [snake(p) for p in params], strict=True):
            rendered = rendered.replace("{" + raw + "}", "{q(" + arg + ")}")
        prefix = "/_sites/{q(site)}" if site_scoped else ""
        full = prefix + rendered
        literal = f'f"{full}"' if "{" in full else f'"{full}"'
        doc = f"{method} {path}" + (f" - {summary}" if summary else "")
        doc = doc.replace("\\", "\\\\").replace('"""', "'''")
        out += [
            "",
            f"def {name}({signature}) -> Route:",
            f'    """{doc}"""' if len(doc) <= 88 else f'    """{method} {path}"""',
            "    return Route(",
            f'        "{op_id}",',
            f'        "{method}",',
            f"        {literal}," + ("  # noqa: E501" if len(literal) > 91 else ""),
            f'        "{auth}",',
            "    )",
            "",
        ]
        template = (("/_sites/{site}" if site_scoped else "") + path).replace('"', '\\"')
        table.append(f'    "{op_id}": ("{method}", "{template}", "{auth}"),')
    out += [
        "",
        "# operationId -> (METHOD, path template, required auth), for lookups by id",
        "OPERATIONS: dict[str, tuple[str, str, str]] = {",
        *table,
        "}",
        "",
    ]
    return "\n".join(out)


ROUTE_MODULE = '''# GENERATED by scripts/gen_routes.py. Do not edit.
"""The `Route` value the generated route builders return (ADR-0005)."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal
from urllib.parse import quote

AuthMode = Literal["none", "bearer", "bearer+user", "bearer+site"]


@dataclass(frozen=True)
class Route:
    """Where one spec operation lives and what auth the spec requires for it."""

    operation_id: str
    method: str
    path: str
    auth: AuthMode

    @classmethod
    def from_table(cls, table: dict[str, tuple[str, str, str]], operation_id: str) -> Route:
        """A route without path parameters, looked up by operationId in an OPERATIONS table."""
        method, path, auth = table[operation_id]
        if "{" in path:
            raise ValueError(f"{operation_id} has path parameters; use its builder")
        return cls(operation_id, method, path, auth)  # type: ignore[arg-type]


def q(value: str) -> str:
    """Percent-encode one path segment (slashes too: nested slugs stay one segment)."""
    return quote(str(value), safe="")
'''


def ruff_format(text: str, path: Path) -> str:
    """Normalise through `ruff format` so the committed file is exactly what CI checks."""
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", str(path), "-"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
        cwd=ROOT,
    )
    return result.stdout


def expected_files() -> dict[Path, str]:
    files = {GENERATED / "route.py": ROUTE_MODULE}
    for spec_name, module, label, site_scoped in TARGETS:
        files[GENERATED / module] = render(spec_name, label, site_scoped)
    return {path: ruff_format(text, path) for path, text in files.items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when committed files drift")
    args = parser.parse_args(argv)
    drift = False
    for path, text in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            continue
        if args.check:
            drift = True
            sys.stdout.writelines(
                difflib.unified_diff(
                    current.splitlines(keepends=True),
                    text.splitlines(keepends=True),
                    f"{path.relative_to(ROOT)} (committed)",
                    f"{path.relative_to(ROOT)} (generated)",
                    n=2,
                )
            )
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if drift:
        print("\ngenerated routes are stale: run `uv run python scripts/gen_routes.py`")
        return 1
    if args.check:
        print("generated routes are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
