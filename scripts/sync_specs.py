"""Vendor the HAXcms NodeJS OpenAPI specs into specs/ (PLAN.md T0.6).

Usage:
    uv run python scripts/sync_specs.py --from ../haxcms-nodejs
    uv run python scripts/sync_specs.py --tag v26.8.1

Copies `system-spec.yaml` and `site-spec.yaml` from the checkout's `src/openapi/`
(or from GitHub raw at a tag) into `specs/` and writes `specs/VERSION`.
"""

from __future__ import annotations

import argparse
import difflib
import json
import shutil
import subprocess
import sys
from pathlib import Path

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from haxcms_mcp.spec_hash import spec_sha256  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
SPECS_DIR = REPO_ROOT / "specs"
SPEC_FILES = ("system-spec.yaml", "site-spec.yaml")
SPEC_INFO_PATH = REPO_ROOT / "src" / "haxcms_mcp" / "generated" / "spec_info.py"
RAW_BASE = "https://raw.githubusercontent.com/haxtheweb/haxcms-nodejs"


def render_spec_info(version: str, commit: str) -> str:
    """The generated module the runtime compatibility check imports (not read from specs/,
    which is not part of an installed package)."""
    system = spec_sha256((SPECS_DIR / "system-spec.yaml").read_bytes())
    site = spec_sha256((SPECS_DIR / "site-spec.yaml").read_bytes())
    return (
        '"""GENERATED by scripts/sync_specs.py - do not edit.\n\n'
        "Identity of the vendored HAXcms specs; compat.py compares the live instance with it.\n"
        '"""\n\n'
        "from __future__ import annotations\n\n"
        f'HAXCMS_VERSION = "{version}"\n'
        f'HAXCMS_COMMIT = "{commit}"\n'
        f'SYSTEM_SPEC_SHA256 = "{system}"\n'
        f'SITE_SPEC_SHA256 = "{site}"\n'
    )


def _write_version(version: str, commit: str) -> None:
    SPECS_DIR.mkdir(parents=True, exist_ok=True)
    (SPECS_DIR / "VERSION").write_text(f"{version} {commit}\n", encoding="utf-8")
    SPEC_INFO_PATH.write_text(render_spec_info(version, commit), encoding="utf-8")
    print(f"wrote {SPEC_INFO_PATH}")


def check_against_checkout(checkout: Path) -> int:
    """Exit 1 with a unified diff when `specs/` differs from the checkout's openapi specs."""
    openapi = checkout / "src" / "openapi"
    drift = False
    for name in SPEC_FILES:
        upstream = (openapi / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        vendored = (SPECS_DIR / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        if upstream == vendored:
            print(f"{name}: up to date")
            continue
        drift = True
        diff = difflib.unified_diff(
            vendored.splitlines(keepends=True),
            upstream.splitlines(keepends=True),
            fromfile=f"specs/{name} (vendored)",
            tofile=f"haxcms-nodejs/src/openapi/{name} (upstream)",
        )
        sys.stdout.writelines(diff)
        print(f"\n{name}: DRIFT")
    if drift:
        print(
            "\nvendored specs are out of date; run `uv run python scripts/sync_specs.py "
            "--from <haxcms-nodejs checkout>` then regenerate with scripts/gen_routes.py, "
            "scripts/gen_tools.py and scripts/gen_tool_docs.py"
        )
        return 1
    return 0


def sync_from_checkout(checkout: Path) -> None:
    openapi = checkout / "src" / "openapi"
    if not openapi.is_dir():
        raise SystemExit(f"error: {openapi} not found; is this a haxcms-nodejs checkout?")
    SPECS_DIR.mkdir(parents=True, exist_ok=True)
    for name in SPEC_FILES:
        src = openapi / name
        if not src.is_file():
            raise SystemExit(f"error: {src} not found")
        shutil.copyfile(src, SPECS_DIR / name)
        print(f"copied {src} -> {SPECS_DIR / name}")

    pkg = json.loads((checkout / "package.json").read_text(encoding="utf-8"))
    version = pkg.get("version", "unknown")
    try:
        commit = subprocess.run(
            ["git", "-C", str(checkout), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        commit = "unknown"
    _write_version(version, commit)
    print(f"wrote {SPECS_DIR / 'VERSION'}: {version} {commit}")


def sync_from_tag(tag: str) -> None:
    SPECS_DIR.mkdir(parents=True, exist_ok=True)
    for name in SPEC_FILES:
        url = f"{RAW_BASE}/{tag}/src/openapi/{name}"
        resp = httpx.get(url, follow_redirects=True, timeout=60)
        if resp.status_code != 200:
            raise SystemExit(f"error: GET {url} -> {resp.status_code}")
        (SPECS_DIR / name).write_bytes(resp.content)
        print(f"downloaded {url} -> {SPECS_DIR / name}")

    pkg_url = f"{RAW_BASE}/{tag}/package.json"
    resp = httpx.get(pkg_url, follow_redirects=True, timeout=60)
    version = "unknown"
    if resp.status_code == 200:
        version = resp.json().get("version", "unknown")
    _write_version(version, tag)
    print(f"wrote {SPECS_DIR / 'VERSION'}: {version} {tag}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--from", dest="checkout", help="path to a local haxcms-nodejs checkout")
    group.add_argument("--tag", help="git tag/ref to download from GitHub")
    parser.add_argument(
        "--check",
        action="store_true",
        help="with --from: do not write; print a diff and exit 1 when specs/ is out of date",
    )
    args = parser.parse_args(argv)
    if args.check:
        if not args.checkout:
            parser.error("--check needs --from <checkout>")
        return check_against_checkout(Path(args.checkout).resolve())
    if args.checkout:
        sync_from_checkout(Path(args.checkout).resolve())
    else:
        sync_from_tag(args.tag)
    return 0


if __name__ == "__main__":
    sys.exit(main())
